/**
 * app/layout.tsx — the root layout wrapping every route in the application.
 *
 * Owns:
 *   - the `<html>`/`<body>` shell and the single global stylesheet import;
 *   - font loading via `next/font` (self-hosted, with a metric-adjusted fallback face);
 *   - the pre-paint theme bootstrap script that prevents a flash of the wrong theme;
 *   - the skip-to-content link, which must be the first focusable element in the document;
 *   - the persistent `Nav` / `main` / `Footer` structure every page renders inside.
 *
 * How it fits: everything on the site is a descendant of this component. The three
 * theming pieces are split across three files that must agree —
 *   `app/globals.css`   resolves `data-theme` into token values (all three states),
 *   this file           sets `data-theme` before first paint,
 *   `lib/useTheme.ts`   reads/updates/persists it at runtime.
 * The storage key `"portfolio-theme"` is duplicated as a literal in the inline script below
 * because that script runs before any module can load; it MUST match
 * `THEME_STORAGE_KEY` in `lib/useTheme.ts`.
 *
 * Metadata here is intentionally minimal — title, description, and viewport-adjacent
 * basics only. Phase 6.2 owns full SEO metadata (Open Graph, canonical, JSON-LD).
 *
 * `LayoutProps<"/">` is generated by the Next.js TypeScript plugin into `.next/types`,
 * which is why `tsconfig.json` must keep that directory in its `include`.
 */
import type { Metadata } from "next";
import { Geist } from "next/font/google";
import Footer from "@/components/Footer";
import Nav from "@/components/Nav";
import { SITE } from "@/lib/site";
import "./globals.css";

/**
 * Primary (and only) typeface: Geist, self-hosted by `next/font` so there is no
 * third-party request.
 *
 * `variable` exposes it as `--font-geist-sans`, which `--font-sans` in `globals.css`
 * consumes at the head of a system fallback stack. One family only: hierarchy on this
 * site is carried by size and whitespace, not by mixing faces.
 *
 * NO `fallback` ARRAY — this omission is load-bearing, do not "helpfully" add one back.
 * When `fallback` is passed explicitly, `next/font` uses those families verbatim and
 * skips generating its metric-adjusted `"Geist Fallback"` `@font-face` (the synthetic
 * face carrying `size-adjust`, `ascent-override`, etc. derived from Geist's own metrics).
 * With `display: "swap"`, that means first paint sets type in SF/Segoe/Roboto at their
 * *own* metrics and then reflows when Geist arrives — visible CLS on the 44px `text-2xl`
 * h1 and the nav row, i.e. the LCP element of every page. Leaving `fallback` off lets
 * Next emit `Geist Fallback` so the pre-swap and post-swap text occupy the same box.
 *
 * Nothing is lost by dropping it: the system stack in `globals.css` (`--font-sans`) sits
 * behind `var(--font-geist-sans)` and is the actual safety net for "next/font failed to
 * load entirely", which is what this comment previously — and wrongly — credited the
 * `fallback` array with providing.
 */
const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
  display: "swap",
});
/**
 * Default document metadata.
 *
 * `title.template` lets each route set only its own leaf title (e.g. `"Projects"`) and still
 * render as `"Projects — Ethan Caldwell"`; `title.default` covers routes that set nothing.
 */
export const metadata: Metadata = {
  title: {
    default: `${SITE.name} — ${SITE.role}`,
    template: `%s — ${SITE.name}`,
  },
  description: SITE.description,
};

/**
 * Inline script that sets `data-theme` on `<html>` before the first paint.
 *
 * Why this exists: the stored preference lives in `localStorage`, which is unreachable
 * during a static server render. Without this, a visitor who chose Dark would see a
 * light page for one frame before React hydrated — the classic theme flash. Running
 * synchronously in `<head>`, before the body paints, is the only way to avoid it.
 *
 * Behaviour:
 *   - stored `"dark"` or `"light"` → set the matching attribute (explicit override);
 *   - anything else, including a throw, a missing key, or an empty string → leave the
 *     attribute OFF, which is the `"system"` state that `globals.css` resolves via
 *     `prefers-color-scheme`. The page therefore renders correctly with no stored value.
 *
 * The try/catch guards `localStorage.getItem` **throwing**: it does so in Safari private
 * browsing, when a browser is configured to block site data, and in a cross-origin iframe
 * without storage access. An uncaught throw in a blocking head script would halt parsing
 * of the rest of the script, so this catch is load-bearing, not defensive noise.
 *
 * Kept as a string constant so the IIFE is minified-by-hand and easy to audit.
 */
const THEME_BOOTSTRAP = `(function(){try{var t=localStorage.getItem("portfolio-theme");if(t==="dark"||t==="light"){document.documentElement.setAttribute("data-theme",t);}}catch(e){}})();`;

/**
 * Root layout.
 *
 * @param props.children - The active route's rendered output; placed inside `<main>`.
 * @returns The full document shell: head-level theme bootstrap, skip link, header, main
 *          landmark, footer.
 *
 * Accessibility notes:
 *   - The skip link is the first element in `<body>` so it is the first thing a keyboard
 *     visitor reaches. It is `sr-only` until focused, then `not-sr-only` renders it as a
 *     visible pill in the top-left. Its target, `#main-content`, carries `tabIndex={-1}`
 *     so browsers actually move focus (not just scroll) when the fragment is followed.
 *   - The link uses `focus:fixed`, NOT `focus:absolute`. There is no positioned ancestor
 *     in this shell, so `absolute` would resolve against the initial containing block —
 *     i.e. the top of the *document*. If focus returned to the link while the visitor was
 *     scrolled down the page (Shift+Tab out of the nav), it would render off-screen above
 *     the viewport and appear to have vanished. `fixed` pins it to the viewport instead.
 *   - It carries no `ring-*` classes: a `ring-<color>` utility does nothing without an
 *     accompanying `ring-<width>`, and the site has exactly one focus treatment — the
 *     global `:focus-visible` outline in `globals.css`. Its border uses `outline`, the
 *     control-boundary token, not the `border` hairline token.
 *   - Exactly one `<main>` in the document; pages must not render another. `app/page.tsx`
 *     and any future route render *inside* this one.
 *
 * Side effects: the inline bootstrap script mutates `<html>`'s `data-theme` attribute.
 *
 * Failure modes: if a strict CSP blocks the inline script, the theme falls back to the
 * system setting for one frame and `lib/useTheme.ts` corrects it on mount — a flash, not
 * a broken page.
 */
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html lang="en" className={`${geistSans.variable} h-full`}>
      <head>
        {/* A plain inline <script>, deliberately not next/script: it must execute
            synchronously during head parsing, which no next/script strategy guarantees. */}
        <script dangerouslySetInnerHTML={{ __html: THEME_BOOTSTRAP }} />
      </head>
      <body className="flex min-h-full flex-col antialiased">
        <a
          href="#main-content"
          className="focus:bg-surface focus:text-fg focus:border-outline sr-only focus:not-sr-only focus:fixed focus:top-3 focus:left-3 focus:z-50 focus:rounded-md focus:border focus:px-4 focus:py-2 focus:text-sm focus:no-underline focus:shadow-lg"
        >
          Skip to main content
        </a>

        <Nav />

        {/* tabIndex={-1}: makes the skip-link target programmatically focusable so focus
            genuinely lands here instead of staying on the link. */}
        <main id="main-content" tabIndex={-1} className="flex-1">
          {children}
        </main>

        <Footer />
      </body>
    </html>
  );
}
